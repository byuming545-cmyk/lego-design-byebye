import type { Connector, GrammarCompatibility, GrammarPlacementResult } from './schema.js';
import type { RigidTransform } from '../assembly/types.js';
import { isRigidTransform, multiply, rotate, transformPoint } from '../assembly/math.js';
import { compareLdu, equalLdu, formatLdu, isMultipleLdu, multiplyLdu, subtractLdu, addLdu, type ExactLdu, type ExactClosureResult } from './exact.js';

export const BUILDING_PATTERN_VERSION = 'connector-topology-patterns-1';
export const BUILDING_PATTERNS = [
  'NORMAL_STACK', 'SNOT_90', 'SNOT_180', 'HALF_STUD_OFFSET', 'PLATE_HEIGHT_OFFSET',
  'BRACKET_OFFSET', 'STUD_IN_SNOT', 'STUD_OUT_SNOT', 'AXIAL_SLIDE', 'AXIAL_ROTATION',
  'HINGE_ANGLE', 'CLIP_BAR_ANGLE', 'BALL_JOINT_ANGLE', 'WHEEL_MOUNT',
  'MULTI_POINT_CONNECTION', 'OFF_GRID_ROTATED_SUBASSEMBLY', 'EXACT_CLOSED_ANGLE',
] as const;
export type BuildingPattern = typeof BUILDING_PATTERNS[number];
export interface BuildingPatternDetection {
  kind: BuildingPattern;
  state: 'TOPOLOGY_POTENTIAL' | 'SOLVED_JOINT' | 'EXACT_CLOSURE';
  featureIds: string[];
  sourceIds: string[];
  /** Exact decimal/rational witness; not rounded stud-grid coordinates. */
  offsetLdu?: [string, string, string];
  occurrences: number;
  notes: string[];
}
export interface PatternJointEvidence {
  featureIds: string[];
  compatibility: GrammarCompatibility;
  placement: GrammarPlacementResult;
  /** Distinct mates checked under the same pose by the multi-point validator. */
  validatedMateCount?: number;
}
export interface PatternContext {
  joints?: readonly PatternJointEvidence[];
  /** Actual accepted subassembly poses; no pose is generated by this classifier. */
  subassemblyTransforms?: readonly RigidTransform[];
  closure?: ExactClosureResult;
}
export interface BuildingPatternResult {
  version: string;
  coordinateSystem: 'ldraw-native';
  units: 'LDU';
  patterns: BuildingPatternDetection[];
  diagnostics: { code: string; message: string }[];
  /** Capability classification never grants fit, stressing or physical-build approval. */
  legalAssemblyEstablished: false;
}

const STUD_SYSTEM = new Set(['STUD', 'HOLLOW_STUD', 'ANTISTUD']);
function male(feature: Connector) { return feature.role === 'MALE' && ['STUD', 'HOLLOW_STUD'].includes(feature.family); }
function receiver(feature: Connector) { return feature.role === 'FEMALE' && feature.family === 'ANTISTUD'; }
function sourceIds(features: readonly Connector[]) { return [...new Set(features.flatMap(feature => feature.sources.map(source => source.id)))].sort(); }
function axisDot(a: readonly number[], b: readonly number[]): ExactLdu {
  return a.reduce((sum, value, axis) => addLdu(sum, multiplyLdu(value, b[axis])), addLdu(0, 0));
}
function exactUnit(axis: readonly number[]): boolean { return axis.length === 3 && axis.every(Number.isFinite) && equalLdu(axisDot(axis, axis), 1); }
function cardinalAxis(axis: readonly number[]): number | undefined {
  if (!exactUnit(axis)) return undefined;
  const coordinate = axis.findIndex(value => equalLdu(value, 1) || equalLdu(value, -1));
  return coordinate >= 0 && axis.every((value, index) => index === coordinate || equalLdu(value, 0)) ? coordinate : undefined;
}
function nonzero(values: readonly (number | ExactLdu)[]) { return values.some(value => !equalLdu(value, 0)); }
function magnitude(value: ExactLdu): ExactLdu { return compareLdu(value, 0) < 0 ? multiplyLdu(value, -1) : value; }
function sourcePositionKnown(feature: Connector): boolean {
  return feature.localPositionLdu.length === 3 && feature.localPositionLdu.every(Number.isFinite)
    && feature.sources.length > 0 && ['SOURCE_BACKED', 'VERIFIED'].includes(feature.confidence)
    // A source label such as internal R4 stud3 is not automatically a C01
    // external System stud. Let the grammar's established feature semantics
    // distinguish these; otherwise a Jumper's internal tube falsely looks like
    // a normal stud-reversal device.
    && feature.coverage === 'COMPLETE' && feature.matchingPolicy?.ruleId === 'C01'
    && !feature.unknownFields.some(field => /position|orientation|axis/.test(field))
    && exactUnit(feature.axis);
}
function jointSources(evidence: PatternJointEvidence): string[] {
  return [...new Set(evidence.compatibility.sourceIds)].sort();
}
function validJointEvidence(evidence: PatternJointEvidence): boolean {
  return evidence.compatibility.status === 'COMPATIBLE' && evidence.placement.status === 'SOLVED'
    && evidence.featureIds.length >= 2 && new Set(evidence.featureIds).size === evidence.featureIds.length
    && evidence.compatibility.ruleId !== null && !!evidence.compatibility.joint && !!evidence.placement.poseFamily
    && evidence.compatibility.joint.type === evidence.placement.poseFamily.type
    && evidence.compatibility.joint.translationDof === evidence.placement.poseFamily.translationDof
    && evidence.compatibility.joint.rotationDof === evidence.placement.poseFamily.rotationDof
    && evidence.compatibility.sourceIds.length > 0 && evidence.placement.candidates.some(candidate => isRigidTransform(candidate.transform));
}
function offGridRotation(transform: RigidTransform): boolean {
  if (!isRigidTransform(transform)) return false;
  // Signed permutations preserve an orthogonal LDraw axis grid. Other actual
  // rotations are off-grid; no epsilon rounds them into a grid orientation.
  return !transform.rotation.every(value => value === 0 || value === 1 || value === -1);
}

/** Classifies connector transforms, never part numbers, names, or pair history.
 * Source snap axes use the LDCad convention: a normal stud and its receiving
 * cavity point along the SAME snap axis. Normal stacking therefore cannot be
 * mistaken for SNOT180 merely because their outward surface normals differ. */
export function classifyBuildingPatterns(connectors: readonly Connector[], context: PatternContext = {}): BuildingPatternResult {
  const result: BuildingPatternResult = { version: BUILDING_PATTERN_VERSION, coordinateSystem: 'ldraw-native', units: 'LDU', patterns: [], diagnostics: [], legalAssemblyEstablished: false };
  const detections = new Map<BuildingPattern, BuildingPatternDetection>();
  const add = (kind: BuildingPattern, features: readonly Connector[], state: BuildingPatternDetection['state'], notes: string[], offset?: readonly ExactLdu[], extraSources: string[] = []) => {
    const found = detections.get(kind);
    if (found) { found.occurrences++; return; }
    detections.set(kind, { kind, state, featureIds: [...new Set(features.map(feature => feature.featureId))], sourceIds: [...new Set([...sourceIds(features), ...extraSources])].sort(), occurrences: 1, notes, ...(offset ? { offsetLdu: offset.map(formatLdu) as [string, string, string] } : {}) });
  };
  const features = connectors.filter(feature => STUD_SYSTEM.has(feature.family) && sourcePositionKnown(feature));
  if (features.length > 1024) {
    result.diagnostics.push({ code: 'topology-budget-exceeded', message: 'More than 1024 stud-system features require a larger explicitly reviewed topology budget; no unexamined topology is classified.' });
  } else for (let i = 0; i < features.length; i++) for (let j = i + 1; j < features.length; j++) {
    const a = features[i], b = features[j], relation = axisDot(a.axis, b.axis);
    const delta = a.localPositionLdu.map((value, axis) => subtractLdu(b.localPositionLdu[axis], value));
    const opposedRoles = male(a) && receiver(b) || receiver(a) && male(b);
    if (equalLdu(relation, 1) && opposedRoles) {
      add('NORMAL_STACK', [a, b], 'TOPOLOGY_POTENTIAL', ['Parallel male/receiving stud-system axes transmit the build direction; fit and collision remain separate.'], delta);
    }
    if (equalLdu(relation, 0)) {
      add('SNOT_90', [a, b], 'TOPOLOGY_POTENTIAL', ['Source-backed stud-system snap axes are exactly perpendicular; this is an available topology, not an assembly certificate.'], delta);
      if (opposedRoles) {
        const input = receiver(a) ? a : b, output = male(a) ? a : b;
        const inAxis = cardinalAxis(input.axis), outAxis = cardinalAxis(output.axis);
        if (inAxis === 1 && outAxis !== undefined && outAxis !== 1) add('STUD_OUT_SNOT', [input, output], 'TOPOLOGY_POTENTIAL', ['Upright receiving axis leads to a side-facing male stud.'], delta);
        if (outAxis === 1 && inAxis !== undefined && inAxis !== 1) add('STUD_IN_SNOT', [input, output], 'TOPOLOGY_POTENTIAL', ['Side-facing receiving axis leads to an upright male stud.'], delta);
      }
      if (nonzero(delta)) add('BRACKET_OFFSET', [a, b], 'TOPOLOGY_POTENTIAL', ['Perpendicular stud-system features have a nonzero source-derived positional offset; this does not identify a part as a bracket.'], delta);
    }
    if (equalLdu(relation, -1)) {
      add('SNOT_180', [a, b], 'TOPOLOGY_POTENTIAL', ['Source snap axes genuinely reverse. This is not inferred from male/female surface normal reversal.'], delta);
    }
    if (equalLdu(relation, 1) && opposedRoles) {
      const axialCoordinate = cardinalAxis(a.axis);
      if (axialCoordinate !== undefined) {
        const radialCoordinates = [0, 1, 2].filter(axis => axis !== axialCoordinate);
        if (radialCoordinates.some(axis => isMultipleLdu(delta[axis], 10) && !isMultipleLdu(delta[axis], 20))
            && radialCoordinates.every(axis => isMultipleLdu(delta[axis], 10))) {
          add('HALF_STUD_OFFSET', [a, b], 'TOPOLOGY_POTENTIAL', ['An input/output stud-system translation has an exact 10 modulo 20 LDU transverse offset.'], delta);
        }
        const axialOffset = magnitude(delta[axialCoordinate]);
        if (!equalLdu(axialOffset, 0) && isMultipleLdu(axialOffset, 8)) {
          add('PLATE_HEIGHT_OFFSET', [a, b], 'TOPOLOGY_POTENTIAL', ['An input/output axial separation is an exact nonzero multiple of 8 LDU; 24 LDU equals one brick.'], delta);
        }
      }
    }
  }
  const known = new Map(connectors.map(feature => [feature.featureId, feature]));
  const validJoints = (context.joints ?? []).filter(validJointEvidence);
  for (const evidence of validJoints) {
    const joint = evidence.compatibility.joint!;
    const selected = evidence.featureIds.map(id => known.get(id)).filter((feature): feature is Connector => !!feature);
    if (selected.length !== new Set(evidence.featureIds).size || selected.some(feature => !feature.sources.length)) {
      result.diagnostics.push({ code: 'joint-features-unresolved', message: 'A solved-joint pattern references a feature or source absent from this topology.' });
      continue;
    }
    const ids = jointSources(evidence), note = ['Derived from an explicitly source-backed compatible, solved joint. Fit, collision, stressing and stability are not granted by this classification.'];
    if (joint.translationDof === 1) add('AXIAL_SLIDE', selected, 'SOLVED_JOINT', note, undefined, ids);
    if (joint.rotationDof === 1) add('AXIAL_ROTATION', selected, 'SOLVED_JOINT', note, undefined, ids);
    if (['HINGE', 'CLICK_HINGE', 'TURNTABLE'].includes(evidence.compatibility.ruleId ?? '')) add('HINGE_ANGLE', selected, 'SOLVED_JOINT', note, undefined, ids);
    if (evidence.compatibility.ruleId === 'BAR_CLIP') add('CLIP_BAR_ANGLE', selected, 'SOLVED_JOINT', note, undefined, ids);
    if (joint.type === 'SPHERICAL') add('BALL_JOINT_ANGLE', selected, 'SOLVED_JOINT', note, undefined, ids);
    if (evidence.compatibility.ruleId === 'WHEEL_MOUNT') add('WHEEL_MOUNT', selected, 'SOLVED_JOINT', note, undefined, ids);
    if ((evidence.validatedMateCount ?? 0) >= 2) add('MULTI_POINT_CONNECTION', selected, 'SOLVED_JOINT', ['At least two distinct mates were checked under the same rigid pose; this is not inferred from a part merely having several studs.'], undefined, ids);
  }
  if (validJoints.length && context.subassemblyTransforms?.some(offGridRotation)) {
    add('OFF_GRID_ROTATED_SUBASSEMBLY', [], 'SOLVED_JOINT', ['An actual source-backed solved articulation has a non-grid subassembly pose. Multi-end reconnection still requires closure.'], undefined, validJoints.flatMap(jointSources));
  }
  if (validJoints.length && context.closure?.status === 'EXACT' && context.closure.exact && context.closure.residuals.length >= 2
      && context.closure.residuals.every(residual => residual.position.every(value => equalLdu(value, 0)) && (!residual.axis || residual.axis.every(value => equalLdu(value, 0))))) {
    add('EXACT_CLOSED_ANGLE', [], 'EXACT_CLOSURE', ['All declared multiple endpoints agree exactly under the one supplied pose. This mathematical closure does not establish material or collision legality.'], undefined, validJoints.flatMap(jointSources));
  }
  if (connectors.some(feature => STUD_SYSTEM.has(feature.family) && !sourcePositionKnown(feature))) result.diagnostics.push({ code: 'topology-feature-unknown', message: 'Some stud-system features lack a source-backed exact unit axis or established position; no rounding or guessed pattern was applied to them.' });
  result.patterns = [...detections.values()];
  return result;
}

export class BuildingPatternClassifier {
  classify(connectors: readonly Connector[], context: PatternContext = {}): BuildingPatternResult { return classifyBuildingPatterns(connectors, context); }
}

export interface PlacedConnectorTopology { instanceId: string; transform: RigidTransform; connectors: readonly Connector[] }
/** A convenience for already solved assemblies: transform all source features
 * into one frame, keeping instance identities. Inter-part patterns are only
 * considered inside the connected components described by solved joint evidence.
 * This never solves or accepts an assembly on behalf of the constraint engine. */
export function classifyAssemblyBuildingPatterns(placements: readonly PlacedConnectorTopology[], context: PatternContext = {}): BuildingPatternResult {
  const features: Connector[] = [], instances = new Map<string, string>(), ids = new Set<string>();
  for (const placement of placements) {
    if (!placement.instanceId || ids.has(placement.instanceId) || !isRigidTransform(placement.transform)) return {
      version: BUILDING_PATTERN_VERSION, coordinateSystem: 'ldraw-native', units: 'LDU', patterns: [], legalAssemblyEstablished: false,
      diagnostics: [{ code: 'invalid-topology-placement', message: 'Assembly topology requires unique instances with proper rigid poses.' }],
    };
    ids.add(placement.instanceId);
    for (const feature of placement.connectors) {
      const featureId = `${placement.instanceId}/${feature.featureId}`;
      instances.set(featureId, placement.instanceId);
      features.push({ ...feature, featureId, localPositionLdu: transformPoint(placement.transform, feature.localPositionLdu), localOrientation: multiply(placement.transform.rotation, feature.localOrientation), axis: rotate(placement.transform.rotation, feature.axis) });
    }
  }
  const adjacency = new Map([...ids].map(id => [id, new Set<string>()]));
  const proven = (context.joints ?? []).filter(validJointEvidence);
  for (const joint of proven) {
    const members = [...new Set(joint.featureIds.map(id => instances.get(id)).filter((id): id is string => id !== undefined))];
    for (const a of members) for (const b of members) if (a !== b) adjacency.get(a)!.add(b);
  }
  const components: Set<string>[] = [], visited = new Set<string>();
  for (const start of ids) {
    if (visited.has(start)) continue;
    const component = new Set<string>(), queue = [start];
    while (queue.length) { const current = queue.pop()!; if (visited.has(current)) continue; visited.add(current); component.add(current); queue.push(...adjacency.get(current)!); }
    components.push(component);
  }
  const results = components.map(component => {
    const selected = features.filter(feature => component.has(instances.get(feature.featureId)!));
    const joints = proven.filter(joint => joint.featureIds.every(id => instances.has(id) && component.has(instances.get(id)!)));
    return classifyBuildingPatterns(selected, { ...context, joints });
  });
  const combined = results.flatMap(result => result.patterns), merged = new Map<BuildingPattern, BuildingPatternDetection>();
  for (const detection of combined) {
    const existing = merged.get(detection.kind);
    if (existing) existing.occurrences += detection.occurrences; else merged.set(detection.kind, { ...detection });
  }
  return { version: BUILDING_PATTERN_VERSION, coordinateSystem: 'ldraw-native', units: 'LDU', patterns: [...merged.values()], diagnostics: results.flatMap(result => result.diagnostics), legalAssemblyEstablished: false };
}
