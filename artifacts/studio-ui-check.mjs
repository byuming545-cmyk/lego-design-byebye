import { chromium } from '@playwright/test';
import fs from 'node:fs/promises';
import path from 'node:path';

const root = process.cwd();
const out = path.join(root, 'artifacts', 'interface-library');
const executablePath = path.join(root, '.playwright-browsers/chrome-headless-shell/chrome-headless-shell-linux64/chrome-headless-shell');
await fs.rm(path.join(root, 'data/interface-library/studio-examples.json'), { force: true });
const browser = await chromium.launch({ executablePath, headless: true, args: ['--no-sandbox', '--disable-dev-shm-usage'] });
const errors = [];
const context = await browser.newContext({ viewport: { width: 1440, height: 1100 }, acceptDownloads: true });
const page = await context.newPage();
page.on('console', message => { if (message.type() === 'error') errors.push(`console: ${message.text()}`); });
page.on('pageerror', error => errors.push(`page: ${error.message}`));
await page.goto('http://127.0.0.1:3001/#/interface-library', { waitUntil: 'networkidle' });
await page.getByRole('button', { name: '看示范' }).click();
await page.locator('.il-case-row').filter({ hasText: '3024' }).first().click();
await page.locator('.case-player').waitFor({ timeout: 30000 });
await page.screenshot({ path: path.join(out, 'case-player.png'), fullPage: false });
await page.getByRole('button', { name: '播放', exact: true }).click();
await page.waitForTimeout(250);
await page.screenshot({ path: path.join(out, 'case-player-playing.png'), fullPage: false });
const downloadPromise = page.waitForEvent('download', { timeout: 60000 });
await page.getByRole('button', { name: '导出 GIF' }).click();
const download = await downloadPromise;
const gifPath = path.join(out, 'case-c01.gif');
await download.saveAs(gifPath);
const gifBytes = (await fs.stat(gifPath)).size;
await page.getByRole('button', { name: '我来拼搭' }).last().click();
await page.locator('.studio').waitFor({ timeout: 30000 });
await page.locator('.studio-case-picker select').waitFor({ timeout: 30000 });
await page.screenshot({ path: path.join(out, 'studio.png'), fullPage: false });
await page.locator('.studio-step-row input').fill('10');
const yPlus = page.locator('.studio-axis-grid > div').nth(1).getByRole('button').last();
await yPlus.click();
await page.waitForTimeout(150);
await page.getByRole('button', { name: '撤销' }).click();
await page.getByRole('button', { name: '重做' }).click();
await page.getByRole('button', { name: '恢复原始位置' }).click();
await page.waitForTimeout(200);
await page.getByRole('button', { name: '记录起始位置' }).click();
await page.getByRole('button', { name: '吸附到来源候选姿态' }).click();
await page.waitForTimeout(300);
await page.getByRole('button', { name: '记录连接完成位置' }).click();
await page.getByLabel('我认为连接在哪里').fill('四个凸点全部进入凹槽');
await page.getByLabel('为什么可以这样连接').fill('浏览器自动验证：C01 标准凸点规则，固定一件零件后移动另一件。');
await page.getByRole('button', { name: '运行检查' }).click();
await page.locator('.studio-result').waitFor({ timeout: 60000 });
await page.screenshot({ path: path.join(out, 'studio-result.png'), fullPage: false });
const resultText = await page.locator('.studio-result').innerText();
await page.getByRole('button', { name: '保存为待验证示例' }).click();
await page.locator('.studio-saved').waitFor({ timeout: 30000 });
const savedText = await page.locator('.studio-saved').innerText();
await page.screenshot({ path: path.join(out, 'studio-saved.png'), fullPage: false });
await page.reload({ waitUntil: 'networkidle' });
await page.getByRole('button', { name: '我来拼搭' }).first().click();
await page.locator('.studio-example-list').waitFor({ timeout: 30000 });
const listText = await page.locator('.studio-example-list').innerText();
await page.getByRole('button', { name: /30374|3024|3070b/ }).first().click();
await page.waitForTimeout(2500);
await page.screenshot({ path: path.join(out, 'studio-reopen.png'), fullPage: false });

const mobile = await context.newPage();
await mobile.setViewportSize({ width: 390, height: 844 });
mobile.on('pageerror', error => errors.push(`mobile page: ${error.message}`));
await mobile.goto('http://127.0.0.1:3001/#/interface-library', { waitUntil: 'networkidle' });
await mobile.getByRole('button', { name: '我来拼搭' }).first().click();
await mobile.locator('.studio').waitFor({ timeout: 30000 });
await mobile.screenshot({ path: path.join(out, 'studio-mobile.png'), fullPage: false });

console.log(JSON.stringify({ gifBytes, resultText, savedText, listText, errors }, null, 2));
await browser.close();
